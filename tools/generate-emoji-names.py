#!/usr/bin/env python3
"""Generates src/GrugBot.Core/Formatting/EmojiNames.tsv from GitHub's gemoji (decision #47).

Usage (from the repo root):

    git clone https://github.com/github/gemoji ../gemoji
    python3 -I tools/generate-emoji-names.py ../gemoji

then commit the changed EmojiNames.tsv. gemoji is MIT-licensed; its notice is in THIRD-PARTY-NOTICES.md.

Each line of the output is one emoji exactly as gemoji spells it (code points in hex, space-separated, so the
file has no invisible characters in it) and the name shown in game, separated by a tab. GrugBot.Core reads the
file as an embedded resource; StandardEmoji.cs says how it's matched against Discord text.

Which name is shown, when gemoji has several:
1. A Discord-style name from OVERRIDES below, for common emoji whose Discord name differs from gemoji's.
2. For a country or region flag (two regional indicator letters), flag_ and the two letters, as Discord shows
   it: the Norwegian flag is flag_no.
3. Otherwise gemoji's first alias made only of a-z, 0-9 and _ (thumbs up is "+1", "thumbsup": thumbsup).
4. If no alias is like that, the first alias with any other character replaced by _ (t-rex: t_rex).
"""

import json
import re
import subprocess
import sys
from pathlib import Path

# Common emoji whose name in Discord's picker differs from gemoji's first plain alias, keyed by that alias.
# Kept small on purpose: everything else uses gemoji's name, which is usually also one Discord accepts.
OVERRIDES = {
    "slightly_smiling_face": "slight_smile",
    "slightly_frowning_face": "slight_frown",
    "upside_down_face": "upside_down",
    "hugs": "hugging",
    "roll_eyes": "rolling_eyes",
    "nerd_face": "nerd",
    "zipper_mouth_face": "zipper_mouth",
    "money_mouth_face": "money_mouth",
    "face_with_thermometer": "thermometer_face",
    "face_with_head_bandage": "head_bandage",
    "cowboy_hat_face": "cowboy",
    "shrug": "person_shrugging",
    "facepalm": "person_facepalming",
    "hankey": "poop",
    "hand": "raised_hand",
    "fist_raised": "fist",
    "fist_oncoming": "punch",
    "crossed_fingers": "fingers_crossed",
    "skull_and_crossbones": "skull_crossbones",
}

PLAIN = re.compile(r"[a-z0-9_]+")
REGIONAL_A = 0x1F1E6


def first_alias(entry):
    aliases = entry["aliases"]
    plain = [a for a in aliases if PLAIN.fullmatch(a)]
    return plain[0] if plain else re.sub(r"[^a-z0-9_]", "_", aliases[0])


def name_for(entry):
    first = first_alias(entry)
    if first in OVERRIDES:
        return OVERRIDES[first]
    points = [ord(c) for c in entry["emoji"]]
    if len(points) == 2 and all(REGIONAL_A <= p <= REGIONAL_A + 25 for p in points):
        return "flag_" + "".join(chr(ord("a") + p - REGIONAL_A) for p in points)
    return first


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: generate-emoji-names.py <path to a gemoji clone>")
    gemoji = Path(sys.argv[1])
    entries = json.loads((gemoji / "db" / "emoji.json").read_text(encoding="utf-8"))
    try:
        commit = subprocess.run(
            ["git", "-C", str(gemoji), "rev-parse", "HEAD"], capture_output=True, text=True, check=True
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        commit = "unknown"

    used = set()
    lines = []
    for entry in entries:
        if not entry.get("emoji") or not entry.get("aliases"):
            continue
        used.add(first_alias(entry))
        name = name_for(entry)
        assert PLAIN.fullmatch(name), name
        points = " ".join(f"{ord(c):04X}" for c in entry["emoji"])
        lines.append(f"{points}\t{name}")

    missing = set(OVERRIDES) - used
    if missing:
        sys.exit(f"OVERRIDES names aliases that are no longer anything's first alias: {sorted(missing)}")

    out = Path(__file__).resolve().parent.parent / "src" / "GrugBot.Core" / "Formatting" / "EmojiNames.tsv"
    header = [
        "# Standard emoji names, shown in game as :name: (decision #47). Generated by tools/generate-emoji-names.py;",
        "# don't edit by hand. Each line: the emoji's code points in hex, a tab, the name.",
        f"# Data from gemoji (https://github.com/github/gemoji) db/emoji.json, commit {commit}.",
        "# gemoji: Copyright (c) 2019 GitHub, Inc. MIT License, full notice in THIRD-PARTY-NOTICES.md.",
    ]
    out.write_text("\n".join(header + lines) + "\n", encoding="ascii", newline="\n")
    print(f"wrote {len(lines)} emoji to {out}")


if __name__ == "__main__":
    main()
